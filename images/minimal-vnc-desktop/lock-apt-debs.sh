#!/usr/bin/env bash
# Resolve the full apt closure of locks/apt-packages.txt and write it to
# locks/apt-debs.tsv: every .deb the image installs, with its sha256.
#
# The build installs those exact files from the prepared artifact context and
# never runs `apt-get update`, so it does not depend on any Ubuntu server being
# up. This script is the only step that reads the Ubuntu snapshot, and it is
# needed only when a pin in apt-packages.txt or the snapshot ID changes.
#
# apt checks the snapshot's InRelease signature against the base image's
# ubuntu-keyring, and every sha256 written here comes from that signed index.
set -euo pipefail

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
PINS="${APT_PINS_FILE:-$SCRIPT_DIR/locks/apt-packages.txt}"
OUT="${APT_DEBS_LOCK:-$SCRIPT_DIR/locks/apt-debs.tsv}"
ARCH="${ARCH:-amd64}"
UBUNTU_SNAPSHOT="${UBUNTU_SNAPSHOT:-$(awk -F '=' '$1 == "UBUNTU_SNAPSHOT" { print $2 }' "$SCRIPT_DIR/locks/ubuntu-snapshot.lock")}"
UBUNTU_IMAGE="${UBUNTU_IMAGE:-$(sed -n 's/^ARG UBUNTU_IMAGE=//p' "$SCRIPT_DIR/Dockerfile")}"
# The base image has no CA bundle; use the one the Dockerfile copies in.
GOLANG_IMAGE="${GOLANG_IMAGE:-$(sed -n 's/^ARG GOLANG_IMAGE=//p' "$SCRIPT_DIR/Dockerfile")}"
# The archive the closure is resolved against. Override only to try the script
# against another archive; the lock's URLs then point there.
APT_SOURCE="${APT_SOURCE:-https://snapshot.ubuntu.com/ubuntu/${UBUNTU_SNAPSHOT}}"
URL_BASE="${URL_BASE:-https://snapshot.ubuntu.com/ubuntu/${UBUNTU_SNAPSHOT}}"

if [[ -z "$UBUNTU_SNAPSHOT" || -z "$UBUNTU_IMAGE" || -z "$GOLANG_IMAGE" ]]; then
  echo "Could not read the snapshot ID or a base image from the Dockerfile" >&2
  exit 1
fi

pins="$(grep -vE '^[[:space:]]*(#|$)' "$PINS" | tr '\n' ' ')"
tmp="$(mktemp)"
certs="$(mktemp -d)"
trap 'rm -rf "$tmp" "$certs"' EXIT
docker run --rm --platform "linux/$ARCH" --entrypoint cat "$GOLANG_IMAGE" \
  /etc/ssl/certs/ca-certificates.crt >"$certs/ca-certificates.crt"

docker run --rm --platform "linux/$ARCH" \
  -v "$certs/ca-certificates.crt:/etc/ssl/certs/ca-certificates.crt:ro" \
  -e APT_SOURCE="$APT_SOURCE" -e URL_BASE="$URL_BASE" -e PINS="$pins" \
  --entrypoint /bin/bash "$UBUNTU_IMAGE" -c '
set -euo pipefail
rm -f /etc/apt/sources.list.d/*
for suite in jammy jammy-updates jammy-backports jammy-security; do
  echo "deb ${APT_SOURCE}/ ${suite} main restricted universe multiverse"
done >/etc/apt/sources.list
printf "Acquire::Check-Valid-Until \"false\";\nAcquire::Retries \"3\";\n" >/etc/apt/apt.conf.d/99snapshot
apt-get update -qq >&2
arch="$(dpkg --print-architecture)"
# Simulate the install the Dockerfile used to run: every package apt would
# unpack, including upgrades of packages already in the base image.
apt-get -s --no-install-recommends install ${PINS} |
  sed -nE "s/^Inst ([^ ]+) (\[[^]]*\] )?\(([^ ]+) .*/\1 \3/p" |
  sort -u >/tmp/closure
# Every pin is either in the closure at its pinned version, or already in the
# base image at it; otherwise the install is not the one the pins describe.
for pin in ${PINS}; do
  name="${pin%%=*}"; version="${pin#*=}"
  if ! grep -qxF "${name} ${version}" /tmp/closure &&
     [[ "$(dpkg-query -W -f="\${Version}" "$name" 2>/dev/null)" != "$version" ]]; then
    echo "Pin ${pin} is neither in the closure nor in the base image" >&2
    exit 1
  fi
done
while read -r name version; do
  stanza="$(apt-cache show --no-all-versions "${name}=${version}")"
  filename="$(printf "%s\n" "$stanza" | sed -n "s/^Filename: //p" | head -n1)"
  sha256="$(printf "%s\n" "$stanza" | sed -n "s/^SHA256: //p" | head -n1)"
  if [[ -z "$filename" || -z "$sha256" ]]; then
    echo "No index entry for ${name}=${version}" >&2
    exit 1
  fi
  printf "%s\t%s\t%s\t%s\t%s\t%s\n" "$arch" "$name" "$version" "${filename##*/}" "${URL_BASE}/${filename}" "$sha256"
done </tmp/closure
' >"$tmp"

count="$(wc -l <"$tmp" | tr -d '[:space:]')"
if [[ "$count" == "0" ]]; then
  echo "Resolved an empty closure" >&2
  exit 1
fi

{
  echo "# Generated by lock-apt-debs.sh from locks/apt-packages.txt; do not edit."
  echo "# Every .deb the image installs from Ubuntu, resolved against snapshot ${UBUNTU_SNAPSHOT}."
  echo "# arch	name	version	filename	url	sha256"
  cat "$tmp"
} >"$OUT"
echo "Wrote ${count} packages to ${OUT#"$SCRIPT_DIR"/}"
